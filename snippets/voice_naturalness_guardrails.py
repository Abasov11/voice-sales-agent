"""
Иллюстративный фрагмент из voice-sales-agent (портфолио-кейс, не рабочая сборка).

Главный вызов проекта: LLM генерирует реплики голосового агента, но её "рабочие"
привычки — дежурные отклики ("Понимаю вас,"), повторение факта, который клиент
уже назвал, и несколько вопросов в одной реплике — на голосе звучат как чек-лист
робота, а не как живой менеджер. Промпт это не лечит надёжно (жалобы на живых
звонках повторялись). Решение — детерминированный слой постобработки ПОСЛЕ LLM:
он не может испортить содержание (не трогает факты), только убирает конкретные,
заранее описанные паттерны, которые выдают бота.
"""
from __future__ import annotations

import re

_FILLER_PREFIXES = (
    "понимаю вас", "понимаю тебя", "понимаю,", "понимаю.", "понимаю!",
    "ясно,", "ясно.", "ясно!", "отлично,", "отлично.",
)


def strip_filler_ack(text: str) -> str:
    """Срезает дежурный отклик в начале реплики ("Понимаю вас, ..."), если
    дальше есть содержательный текст — главный маркер "робота" в жалобах."""
    t = (text or "").strip()
    low = t.lower()
    for pfx in _FILLER_PREFIXES:
        if low.startswith(pfx) and len(t) - len(pfx) > 20:
            rest = t[len(pfx):].lstrip(" ,.!—-")
            if rest:
                return rest[0].upper() + rest[1:]
    return t


_KNOWN_ECHO_RE = re.compile(r"^Про\s+[^.?!—\-]{1,55}?\s*[.—\-]+\s+")


def strip_known_facts_echo(text: str) -> str:
    """LLM получает в промпте уже известные факты (район, возраст ребёнка),
    чтобы не переспрашивать их, но иногда зачитывает их квитанцией в начале
    реплики ("Про район и возраст — ..."). Срезаем только этот короткий
    лидирующий фрагмент, и только если после него остаётся содержание."""
    t = (text or "").strip()
    m = _KNOWN_ECHO_RE.match(t)
    if m and len(t) - m.end() > 15:
        rest = t[m.end():].lstrip()
        return rest[0].upper() + rest[1:] if rest else t
    return t


def one_question_per_turn(text: str) -> str:
    """По телефону на реплику должен быть ровно один вопрос — несколько
    вопросов подряд ("...вечером? В субботу удобно? Whatsapp на этом номере?")
    клиент не успевает разобрать и теряет нить. Если вопросов 2+, оставляем
    текст по первый включительно; остальное прозвучит на следующих ходах."""
    t = (text or "").strip()
    if t.count("?") < 2:
        return t
    idx = t.find("?")
    return t[: idx + 1].strip()


def clean_reply(raw_llm_text: str) -> str:
    """Собирает guardrails в пайплайн постобработки ответа модели. Порядок
    важен: сначала снимаем дежурные зачины, потом схлопываем до одного
    вопроса — иначе "лишний" вопрос мог остаться от уже срезанного фрагмента."""
    text = strip_filler_ack(raw_llm_text)
    text = strip_known_facts_echo(text)
    return one_question_per_turn(text)


if __name__ == "__main__":
    print(strip_filler_ack("Понимаю вас, вечером записей уже нет."))
    print(strip_known_facts_echo("Про район и возраст — учла, вечером записей уже нет."))
    print(one_question_per_turn("Вам вечером удобно? А в субботу расписание подходит?"))
    print(clean_reply("Понимаю вас, вечером удобно? А в субботу расписание подходит?"))
